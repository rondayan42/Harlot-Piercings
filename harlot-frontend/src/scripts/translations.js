const SANITY_TRANSLATIONS = window.SANITY_TRANSLATIONS || { he: {}, en: {} };

const TRANSLATIONS = {
  he: { ...STATIC_TRANSLATIONS.he, ...SANITY_TRANSLATIONS.he },
  en: { ...STATIC_TRANSLATIONS.en, ...SANITY_TRANSLATIONS.en },
};

/* ── i18n Engine ── */
let currentLang = 'he';

function applyLanguage(lang) {
  const t = TRANSLATIONS[lang];
  const isRTL = lang === 'he';

  // Set html lang + dir
  document.documentElement.lang = lang;
  document.documentElement.dir = isRTL ? 'rtl' : 'ltr';

  // Toggle body class for font swapping
  document.body.classList.toggle('lang-he', isRTL);
  document.body.classList.toggle('lang-en', !isRTL);

  // Apply text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const attr = el.dataset.i18nAttr;
    if (!t[key]) return;

    if (attr) {
      // For attributes like placeholder, content
      el.setAttribute(attr, t[key].replace(/<br>/g, '\n'));
    } else {
      // For innerHTML (supports <br> in translations)
      el.innerHTML = t[key];
    }
  });

  // Update toggle button label
  const btn = document.getElementById('langToggle');
  if (btn) btn.textContent = isRTL ? 'EN' : 'עב';

  currentLang = lang;
  localStorage.setItem('harlot-lang', lang);
}

function initI18n() {
  // Respect saved preference, fall back to Hebrew
  const saved = localStorage.getItem('harlot-lang') || 'he';
  applyLanguage(saved);

  document.getElementById('langToggle').addEventListener('click', () => {
    applyLanguage(currentLang === 'he' ? 'en' : 'he');
  });
}

// Run on load
initI18n();
